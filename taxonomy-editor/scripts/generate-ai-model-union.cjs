// t/3517: `AIModel` is the one piece of the ai-models.json registry that genuinely
// cannot be derived at runtime — TS types are erased before the JS ever runs, and a
// direct `typeof import('../ai-models.json')` widens every id to `string` (verified
// empirically, t/3517#3 — the very typo protection this exists for silently vanishes).
// This script is the minimal alternative TL approved over a new blocking gate: codegen
// the literal union once, commit it, and let a vitest staleness check (not a new CI
// gate — it's one more assertion inside the already-blocking `vitest run` step) catch
// a forgotten regen after ai-models.json changes.
//
// Usage: node scripts/generate-ai-model-union.cjs [--check]
//   (no args)  regenerate generatedAIModelIds.ts in place
//   --check    exit 1 if the committed file is stale, without writing (used by the
//              staleness test's underlying logic — see generateAIModelUnionSource below,
//              which the test imports directly rather than shelling out to this flag)

'use strict';

const fs = require('fs');
const path = require('path');

const REPO_ROOT = path.resolve(__dirname, '..', '..');
const CONFIG_PATH = path.join(REPO_ROOT, 'ai-models.json');
const OUTPUT_PATH = path.join(
  __dirname, '..', 'src', 'renderer', 'hooks', 'useTaxonomyStore', 'slices', 'generatedAIModelIds.ts',
);

/**
 * Pure: config -> generated file source. No I/O — both the CLI and the staleness
 * vitest test call this directly, so there is exactly one place the format lives.
 */
function generateAIModelUnionSource(config) {
  const ids = config.models.map((m) => m.id);
  const seen = new Set();
  const unique = ids.filter((id) => (seen.has(id) ? false : (seen.add(id), true)));
  const union = unique.map((id) => `  | '${id}'`).join('\n');
  return `// Copyright (c) 2026 Jeffrey Snover. All rights reserved.
// Licensed under the MIT License. See LICENSE file in the project root.

// AUTO-GENERATED by taxonomy-editor/scripts/generate-ai-model-union.cjs — do not hand-edit.
// Source of truth: ai-models.json (repo root). Regenerate after any models[] change:
//   node scripts/generate-ai-model-union.cjs
// A vitest staleness check (deriveModelsByBackend.test.ts) fails CI if this file and
// ai-models.json disagree — see t/3517.
export type AIModel =
${union};
`;
}

function main() {
  const config = JSON.parse(fs.readFileSync(CONFIG_PATH, 'utf8'));
  const source = generateAIModelUnionSource(config);

  if (process.argv.includes('--check')) {
    const current = fs.existsSync(OUTPUT_PATH) ? fs.readFileSync(OUTPUT_PATH, 'utf8') : null;
    if (current !== source) {
      console.error(`generatedAIModelIds.ts is stale — run: node ${path.relative(REPO_ROOT, __filename)}`);
      process.exit(1);
    }
    console.log('generatedAIModelIds.ts is up to date.');
    return;
  }

  fs.writeFileSync(OUTPUT_PATH, source);
  console.log(`Wrote ${path.relative(REPO_ROOT, OUTPUT_PATH)} (${config.models.length} model ids).`);
}

if (require.main === module) main();

module.exports = { generateAIModelUnionSource };
